package keys

import (
	"bytes"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

// SopsCreationRuleRegex is the path_regex SopsHQ writes into .sops.yaml. It
// matches the project's encrypted secret files (e.g. secrets.yaml,
// secrets.prod.yml).
const SopsCreationRuleRegex = `secrets.*\.ya?ml$`

// ManagedHeaderPrefix is the first line SopsHQ writes into every .sops.yaml it
// generates. A file whose first non-blank bytes are this prefix is SopsHQ-managed;
// anything else is hand-authored, and SopsHQ never moves or deletes it.
const ManagedHeaderPrefix = "# Generated by SopsHQ"

// utf8BOM is the UTF-8 byte-order mark an editor may prepend when re-saving a
// file. IsManaged skips it (plus ASCII whitespace) before the header check.
var utf8BOM = []byte{0xEF, 0xBB, 0xBF}

// IsManaged reports whether a .sops.yaml's content was generated by SopsHQ (it
// begins with ManagedHeaderPrefix). It tolerates a leading BOM and whitespace so
// an editor that re-saved the file still reads as managed. A hand-authored file
// returns false, which is the signal never to move or delete it.
func IsManaged(content []byte) bool {
	trimmed := bytes.TrimPrefix(content, utf8BOM)
	trimmed = bytes.TrimLeft(trimmed, " \t\r\n")
	return bytes.HasPrefix(trimmed, []byte(ManagedHeaderPrefix))
}

// Recipient pairs a public age recipient with a human label (an OS user or key
// name). The label is documentation only; it appears in a comment, never in the
// value SOPS parses.
type Recipient struct {
	Label string // who this recipient belongs to (for the comment block)
	Age   string // age1... public recipient
}

// SopsYAML renders the full .sops.yaml content for a set of recipients. Output
// is deterministic (recipients sorted by their age value) so re-generating an
// unchanged set produces byte-identical output and clean diffs. A header marks
// the file as generated, and a comment block records who each recipient is.
func SopsYAML(recipients []Recipient) string {
	rs := append([]Recipient(nil), recipients...)
	sort.Slice(rs, func(i, j int) bool { return rs[i].Age < rs[j].Age })

	var b strings.Builder
	b.WriteString(ManagedHeaderPrefix + " - do not hand-edit.\n")
	b.WriteString("# Recipients are managed in the SopsHQ panel; changes here are overwritten.\n")
	if len(rs) > 0 {
		b.WriteString("# Recipients:\n")
		for _, r := range rs {
			label := sanitizeComment(r.Label)
			fmt.Fprintf(&b, "#   %s -> %s\n", label, r.Age)
		}
	}
	b.WriteString("creation_rules:\n")
	fmt.Fprintf(&b, "  - path_regex: %s\n", SopsCreationRuleRegex)
	ages := make([]string, len(rs))
	for i, r := range rs {
		ages[i] = r.Age
	}
	fmt.Fprintf(&b, "    age: %s\n", strings.Join(ages, ","))
	return b.String()
}

// WriteSopsYAML writes .sops.yaml into dir atomically (temp file + rename).
func WriteSopsYAML(dir string, recipients []Recipient) error {
	content := SopsYAML(recipients)
	path := filepath.Join(dir, ".sops.yaml")
	tmp := path + ".tmp"
	if err := os.WriteFile(tmp, []byte(content), 0o644); err != nil {
		return fmt.Errorf("keys: write .sops.yaml: %w", err)
	}
	if err := os.Rename(tmp, path); err != nil {
		return fmt.Errorf("keys: rename .sops.yaml: %w", err)
	}
	return nil
}

// sanitizeComment keeps a label on a single comment line.
func sanitizeComment(s string) string {
	s = strings.ReplaceAll(s, "\r", " ")
	s = strings.ReplaceAll(s, "\n", " ")
	s = strings.TrimSpace(s)
	if s == "" {
		return "(unnamed)"
	}
	return s
}

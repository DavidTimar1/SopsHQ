package place

import (
	"os"
	"strings"
)

// Inspection reports what SOPS/age state ALREADY EXISTS at a placement target,
// gathered without changing anything on disk. SopsHQ consults it before wiring so
// it never silently overwrites a pre-existing key store, env var, or .sops.yaml.
//
// SECURITY: this struct records only NON-secret facts (paths, presence flags, the
// public recipient). It deliberately does NOT carry the on-disk private key. The
// private key is read separately and only at the moment it is sealed into the
// vault (see ReadPrivateKey), so it never lands in a value that might be logged,
// rendered, or returned to the panel.
type Inspection struct {
	// KeysTxtPath is the private key file SopsHQ would write (<base>/keys.txt).
	KeysTxtPath string
	// KeysTxtExists is true when that file is present and non-empty (an empty or
	// missing file is not treated as pre-existing state worth asking about).
	KeysTxtExists bool
	// KeysTxtRecipient is the PUBLIC recipient derived from the on-disk private
	// key (age1...), or "" if it could not be derived (e.g. age-keygen missing, or
	// the file does not parse as an age key). Public, safe to display.
	KeysTxtRecipient string

	// EnvKeyFile is the value of SOPS_AGE_KEY_FILE as the operator currently has it
	// persisted (User scope on Windows; left empty on Linux where it lives in a
	// shell rc file we cannot read authoritatively from the process). Empty means
	// "not set".
	EnvKeyFile string
	// EnvPointsElsewhere is true when SOPS_AGE_KEY_FILE is set AND points at a path
	// other than the one SopsHQ would write. Re-pointing it could hide another
	// project's key, so this is a thing to ask about.
	EnvPointsElsewhere bool

	// SopsYAMLPath is the project's .sops.yaml SopsHQ would write.
	SopsYAMLPath string
	// SopsYAMLExists is true when that file is already present.
	SopsYAMLExists bool
	// SopsYAMLManaged is true when the existing .sops.yaml carries SopsHQ's own
	// generated-file header (so re-creating it is not a real loss of hand-authored
	// config).
	SopsYAMLManaged bool
}

// AnyExisting reports whether the inspection found ANY pre-existing artifact that
// SopsHQ would otherwise overwrite. When false, wiring can proceed without asking.
func (i Inspection) AnyExisting() bool {
	return i.KeysTxtExists || i.EnvPointsElsewhere || i.SopsYAMLExists
}

// managedHeader is the first-line marker SopsHQ writes into every .sops.yaml it
// generates (see keys.SopsYAML). Used to tell an own file from a hand-authored
// one. Kept in sync with that writer.
const managedHeader = "# Generated by SopsHQ"

// Inspect reports the pre-existing SOPS/age state at a placement target WITHOUT
// modifying anything. base is the key-store directory SopsHQ would use;
// projectDir is the project folder whose .sops.yaml SopsHQ would write (may be ""
// to skip the project-file check).
//
// It reads the on-disk private key only to derive its PUBLIC recipient (via
// age-keygen -y, which never emits the private half), so the result carries no
// secret. Reading the persisted SOPS_AGE_KEY_FILE is OS-specific (currentEnvKeyFile).
func Inspect(base, projectDir string) Inspection {
	insp := Inspection{
		KeysTxtPath: KeyFile(base),
	}

	if data, err := os.ReadFile(insp.KeysTxtPath); err == nil && len(strings.TrimSpace(string(data))) > 0 {
		insp.KeysTxtExists = true
		// Best-effort: derive the public recipient. Never store the private half.
		if rec, err := recipientFromPrivateBytes(data); err == nil {
			insp.KeysTxtRecipient = rec
		}
	}

	if env := currentEnvKeyFile(); env != "" {
		insp.EnvKeyFile = env
		if !samePath(env, insp.KeysTxtPath) {
			insp.EnvPointsElsewhere = true
		}
	}

	if projectDir != "" {
		insp.SopsYAMLPath = sopsYAMLPath(projectDir)
		if data, err := os.ReadFile(insp.SopsYAMLPath); err == nil {
			insp.SopsYAMLExists = true
			insp.SopsYAMLManaged = strings.HasPrefix(strings.TrimSpace(string(data)), managedHeader)
		}
	}

	return insp
}
